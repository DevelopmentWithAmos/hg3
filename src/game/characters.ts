const rosterRegistry: CharacterDefinition[] = [...BASE_ROSTER];

export function getAllCharacters(): CharacterDefinition[] {
  return rosterRegistry;
}

export function getPlayableCharacters(): CharacterDefinition[] {
  return rosterRegistry.filter((c) => c.unlocked);
}

export function getCharacterById(id: string): CharacterDefinition {
  return (
    rosterRegistry.find((c) => c.id === id) ??
    rosterRegistry[0]
  );
}

/**
 * Extensibility hook for registering licensed guest fighters at runtime
 * or from future DLC manifests without touching combat, AI, or HUD code.
 */
export function registerGuestCharacter(definition: CharacterDefinition): void {
  const existingIdx = rosterRegistry.findIndex((c) => c.id === definition.id);
  if (existingIdx >= 0) {
    rosterRegistry[existingIdx] = definition;
  } else {
    rosterRegistry.push(definition);
  }
}

export function getDefaultOpponentFor(playerId: string): string {
  const playable = getPlayableCharacters();
  const rival = playable.find((c) => c.id !== playerId);
  return rival ? rival.id : playable[0].id;
}
