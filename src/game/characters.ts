const charImg = (filename: string): string =>
  encodeURI(`/src/assets/images/${filename}`);

interface QuickFighterSeed {
  id: string;
  name: string;
  title: string;
  tagline: string;
  bio: string;
  portraitFile?: string;
  portraitUrl?: string;
  spriteCharacterId?: string;
  faceCrop: FaceCropSpec;
  sleeveStyle?: SleeveStyle;
  sleeveColor?: string;
  chestEmblem?: ChestEmblemStyle;
  rosterGroup: 'creators' | 'politicians' | 'bollywood';
  archetype: string;
  animationStyle: AnimationStyle;
  victoryStyle: VictoryStyle;
  defeatStyle: DefeatStyle;
  outfitStyle: OutfitStyle;
  headgear?: HeadgearStyle;
  hairStyle: HairStyle;
  facialHair: FacialHairStyle;
  glasses?: boolean;
  mufflerColor?: string;
  bodyScale?: [number, number, number];
  suitPrimary: string;
  suitSecondary: string;
  shorts?: string;
  glove?: string;
  skin?: string;
  hair: string;
  accent: string;
  maxHealth: number;
  speed: number; // display 45..98
  power: number; // display 55..98
  defense: number; // display 48..98
  specialName: string;
  specialDesc: string;
  specialAnim: SpecialAnimType;
  callout: string;
}

function makeRosterFighter(seed: QuickFighterSeed): CharacterDefinition {
  const spdMult = Number((0.84 + ((seed.speed - 50) / 50) * 0.34).toFixed(2));
  const pwrMult = Number((0.88 + ((seed.power - 55) / 45) * 0.32).toFixed(2));
  const defMult = Number((0.86 + ((seed.defense - 50) / 50) * 0.32).toFixed(2));
  const jumpMult = Number((0.92 + (spdMult - 0.9) * 0.6).toFixed(2));
  const atkSpdMult = Number((0.9 + (spdMult - 0.9) * 0.75).toFixed(2));
  const specDmg = Math.round(23 + (seed.power - 60) * 0.2);
  const skin = seed.skin ?? '#d89b72';
  const cheek = seed.skin === '#e85d4a' ? '#c93c2b' : '#b8764e';

  return {
    id: seed.id,
    name: seed.name,
    title: seed.title,
    tagline: seed.tagline,
    bio: seed.bio,
    portraitUrl: seed.portraitUrl ?? (seed.portraitFile ? charImg(seed.portraitFile) : undefined),
    spriteCharacterId: seed.spriteCharacterId,
    faceCrop: seed.faceCrop,
    sleeveStyle: seed.sleeveStyle ?? 'short',
    sleeveColor: seed.sleeveColor,
    chestEmblem: seed.chestEmblem,
    category: 'original',
    unlocked: true,
    rosterGroup: seed.rosterGroup,
    archetype: seed.archetype,
    animationStyle: seed.animationStyle,
    victoryStyle: seed.victoryStyle,
    defeatStyle: seed.defeatStyle,
    headgear: seed.headgear ?? 'propeller_cap',
    outfitStyle: seed.outfitStyle,
    hairStyle: seed.hairStyle,
    facialHair: seed.facialHair,
    glasses: seed.glasses,
    mufflerColor: seed.mufflerColor,
    bodyScale: seed.bodyScale ?? [1.0, 1.0, 1.0],
    palette: {
      suitPrimary: seed.suitPrimary,
      suitSecondary: seed.suitSecondary,
      shorts: seed.shorts ?? '#1e293b',
      glove: seed.glove ?? '#f8fafc',
      gloveCuff: seed.accent,
      belt: '#1e293b',
      buckle: seed.accent,
      shoe: '#0f172a',
      skin,
      cheek,
      iris: '#18181b',
      hair: seed.hair,
      accent: seed.accent,
    },
    stats: {
      maxHealth: seed.maxHealth,
      speedMultiplier: spdMult,
      powerMultiplier: pwrMult,
      defenseMultiplier: defMult,
      jumpMultiplier: jumpMult,
      attackSpeedMultiplier: atkSpdMult,
      displayPower: seed.power,
      displaySpeed: seed.speed,
      displayDefense: seed.defense,
    },
    special: {
      name: seed.specialName,
      description: seed.specialDesc,
      animType: seed.specialAnim,
      shockwaveColor: seed.accent,
      calloutText: seed.callout,
      damage: specDmg,
      cooldown: seed.speed > 84 ? 3.8 : 4.6,
      duration: 0.58,
      activeStart: 0.42,
      activeEnd: 0.76,
      hitboxRadius: 1.85,
      knockback: 10.5,
      stunDuration: 0.68,
    },
  };
}

