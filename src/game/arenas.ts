export function getArenaById(id: ArenaId): ArenaDefinition {
  return ARENA_LIST.find((a) => a.id === id) ?? ARENA_LIST[0];
}

export type HazardPhase = 'calm' | 'warning' | 'active';

export function getHazardPhase(
  hazard: ArenaHazardSpec,
  arenaTime: number,
): HazardPhase {
  if (hazard.cyclePeriod <= 0) return 'active';
  const norm = ((arenaTime + hazard.phaseOffset) % hazard.cyclePeriod) / hazard.cyclePeriod;
  if (norm >= hazard.activeStart && norm <= hazard.activeEnd) return 'active';
  if (norm >= hazard.warnStart && norm < hazard.activeStart) return 'warning';
  return 'calm';
}
